import { defineArrayMember, defineField, defineType } from "sanity";

export const product = defineType({
  name: "product",
  title: "Producto",
  type: "document",
  groups: [
    { name: "general", title: "General", default: true },
    { name: "specs", title: "Ficha técnica" },
    { name: "photos", title: "Fotos" },
    { name: "variants", title: "Variantes" },
    { name: "downloads", title: "Descargas" },
  ],
  fields: [
    defineField({
      name: "title",
      title: "Nombre",
      type: "string",
      group: "general",
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: "slug",
      title: "Slug",
      type: "slug",
      group: "general",
      description:
        "Parte de la URL (/productos/slug). No cambiarlo una vez publicado: los favoritos y proyectos de los usuarios lo usan para encontrar el producto.",
      options: { source: "title" },
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: "order",
      title: "Orden",
      type: "number",
      group: "general",
      description: "Posición en el catálogo (de menor a mayor).",
    }),
    defineField({
      name: "format",
      title: "Formato",
      type: "reference",
      to: [{ type: "format" }],
      group: "general",
      description:
        "Mosaik, Brik o Skala. Es también el filtro inicial del catálogo (la escala que elige el usuario).",
    }),
    defineField({
      name: "material",
      title: "Material",
      type: "reference",
      to: [{ type: "material" }],
      group: "general",
      description: "El de todas las variantes, salvo las que indiquen otro.",
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: "application",
      title: "Aplicación",
      type: "reference",
      to: [{ type: "application" }],
      group: "general",
      description: "La de todas las variantes, salvo las que indiquen otra.",
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: "chipSize",
      title: "Medida chip",
      type: "string",
      group: "specs",
      description: "Por ejemplo: 150x20 mm.",
    }),
    defineField({
      name: "meshSize",
      title: "Medida malla",
      type: "string",
      group: "specs",
      description: "Por ejemplo: 302x310 mm.",
    }),
    defineField({
      name: "meshesPerBox",
      title: "Mallas por caja",
      type: "number",
      group: "specs",
      validation: (rule) => rule.integer().min(0),
    }),
    defineField({
      name: "m2PerBox",
      title: "M² por caja",
      type: "number",
      group: "specs",
      description: "Con punto decimal, por ejemplo 0.98. En el sitio se muestra con coma.",
      validation: (rule) => rule.min(0),
    }),
    defineField({
      name: "image",
      title: "Imagen",
      type: "image",
      group: "photos",
      description: "La de la grilla del catálogo y la página del producto.",
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: "hoverImage",
      title: "Imagen al pasar el mouse",
      type: "image",
      group: "photos",
      description: "Versión blanca para el hover de la grilla. Vacío = usa la imagen principal.",
    }),
    defineField({
      name: "samplePhotos",
      title: "Fotos de muestra",
      type: "array",
      group: "photos",
      description: "Fotos de ambiente. Las variantes sin fotos propias usan estas.",
      of: [defineArrayMember({ type: "image" })],
      options: { layout: "grid" },
    }),
    defineField({
      name: "variants",
      title: "Variantes",
      type: "array",
      group: "variants",
      of: [defineArrayMember({ type: "variant" })],
      validation: (rule) => rule.required().min(1),
    }),
    defineField({
      name: "downloads",
      title: "Descargas",
      type: "array",
      group: "downloads",
      description: "Archivos para todas las variantes (plano, ficha, modelo 3D).",
      of: [defineArrayMember({ type: "download" })],
    }),
  ],
  orderings: [
    {
      title: "Orden del catálogo",
      name: "orderAsc",
      by: [{ field: "order", direction: "asc" }],
    },
  ],
  preview: {
    select: { title: "title", variants: "variants", media: "image" },
    prepare: ({ title, variants, media }) => ({
      title,
      subtitle: `${variants?.length ?? 0} variantes`,
      media,
    }),
  },
});
